"""Rebuild the generated geodata files in ../data from their public sources.

    python3 london-atlas/scripts/build_geodata.py

Sources
  - oobrien/vis tubecreature data (tfl_lines.json, tfl_stations.json): OpenStreetMap-derived
    TfL network geometry, ODbL. Filtered to services operating in 2026.
"""
import json
import pathlib
import urllib.request

DATA = pathlib.Path(__file__).resolve().parent.parent / "data"
OOBRIEN = "https://raw.githubusercontent.com/oobrien/vis/master/tubecreature/data/"
YEAR = 2026
BBOX = (-0.42, 51.38, 0.12, 51.65)  # inner London plus a margin
DROP = {"Crossrail 2", "East London"}  # proposed / pre-2010 services


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return json.load(r)


def running(line):
    if line["name"] in DROP or line.get("opened", 0) > YEAR:
        return False
    return not ("closed" in line and line["closed"] <= YEAR)


def rename(name):
    return "Thameslink" if name.startswith("Thameslink") else name


def inside(c):
    return BBOX[0] <= c[0] <= BBOX[2] and BBOX[1] <= c[1] <= BBOX[3]


def write_js(name, var, obj):
    body = json.dumps(obj, separators=(",", ":"), ensure_ascii=False)
    (DATA / name).write_text(f"/* generated by scripts/build_geodata.py — see README for provenance */\nwindow.{var}={body};\n")


def transport():
    src = ("Derived from oobrien/vis tubecreature data (tfl_lines.json, tfl_stations.json), itself built from "
           f"OpenStreetMap (ODbL) and TfL open data. Filtered to services operating in {YEAR}; future/closed services removed.")
    lines, stations = [], []
    for f in fetch(OOBRIEN + "tfl_lines.json")["features"]:
        names = sorted({rename(l["name"]) for l in f["properties"]["lines"] if running(l)})
        coords = f["geometry"]["coordinates"]
        if names and any(inside(c) for c in coords):
            lines.append({"type": "Feature", "properties": {"lines": names},
                          "geometry": {"type": "LineString", "coordinates": [[round(x, 5), round(y, 5)] for x, y in coords]}})
    for f in fetch(OOBRIEN + "tfl_stations.json")["features"]:
        p, c = f["properties"], f["geometry"]["coordinates"]
        names = sorted({rename(l["name"]) for l in p["lines"] if running(l)})
        if names and inside(c):
            stations.append({"type": "Feature", "properties": {"id": p["id"], "name": p["name"], "lines": names, "zone": p.get("zone")},
                             "geometry": {"type": "Point", "coordinates": [round(c[0], 5), round(c[1], 5)]}})
    write_js("transport-lines.js", "ATLAS_LINES", {"type": "FeatureCollection", "source": src, "features": lines})
    write_js("stations.js", "ATLAS_STATIONS", {"type": "FeatureCollection", "source": src, "features": stations})
    print(f"transport: {len(lines)} segments, {len(stations)} stations")


if __name__ == "__main__":
    transport()
