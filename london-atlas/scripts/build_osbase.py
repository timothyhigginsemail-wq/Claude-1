"""Build data/osbase.js — a vector base map from Ordnance Survey open data (OGL), via the
UCL CASA teaching repository jreades/fsds (GeoPackages in British National Grid):

  Boroughs.gpkg   London Datastore borough boundaries *excluding* the Thames at mean high water,
                  so the river is the gap between them (drawn as water underneath).
  Greenspace.gpkg OS Open Greenspace "Public Park Or Garden" polygons.
  Roads.gpkg      OS Open Roads motorways and A roads.

    python3 london-atlas/scripts/build_osbase.py
"""
import json, math, pathlib, sqlite3, sys, tempfile, urllib.request
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from gpkg import geom, bng2wgs, dp

SRC = "https://raw.githubusercontent.com/jreades/fsds/master/data/src/"
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "osbase.js"
# BNG boxes (metres)
INNER = (515000, 170000, 545000, 192000)   # parks, lakes
ROADBOX = (520000, 173000, 540000, 188500)  # A roads


def get(name):
    p = pathlib.Path(tempfile.gettempdir()) / ("osbase-" + name)
    if not p.exists():
        urllib.request.urlretrieve(SRC + name, p)
    return sqlite3.connect(p)


def conv(pts, tol, nd=5):
    out = []
    for x, y in dp(pts, tol):
        la, lo = bng2wgs(x, y)
        out.append([round(la, nd), round(lo, nd)])
    return out


def polys(g):
    return g[1] if g[0] == 'M' else [g]


def bbox_hit(pts, box):
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    return not (max(xs) < box[0] or min(xs) > box[2] or max(ys) < box[1] or min(ys) > box[3])


def area(r):
    return abs(sum(r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1] for i in range(len(r)))) / 2


land = []
for name, inner, blob in get("Boroughs.gpkg").execute("select NAME, ONS_INNER, geom from Boroughs"):
    rings = []
    for p in polys(geom(blob)):
        for r in p[1]:
            if area(r) > 2000:
                rings.append(conv(r, 3) if inner == "T" else conv(r, 12, 4))
    land.append({"n": name, "inner": inner == "T", "r": rings})

# Water.gpkg (OS Meridian 2 lakes/docks) is not used: its polygons sit 300-400 m south of the true
# features (Serpentine, St James's Park lake), by inconsistent amounts, so it cannot be corrected.
water = []

green = []
for name, blob in get("Greenspace.gpkg").execute("select distName1, geom from Greenspace"):
    for p in polys(geom(blob)):
        outer = p[1][0]
        if not bbox_hit(outer, INNER):
            continue
        ha = area(outer) / 10000
        if ha < 0.4:
            continue
        green.append({"n": name or "", "ha": round(ha, 1), "r": [conv(r, 3) for r in p[1] if area(r) > 50]})

groups = {}
for name, num, cls, blob in get("Roads.gpkg").execute("select DISTNAME, ROADNUMBER, CLASSIFICA, geom from Roads"):
    for l in polys(geom(blob)):
        pts = l[1]
        if bbox_hit(pts, ROADBOX):
            key = (name or "", num or "", cls.startswith("Motorway"))
            groups.setdefault(key, []).append(conv(pts, 8, 4))
# one entry per named road: {n: name, no: number, m: motorway?, l: [polylines]}
roads = [{"n": k[0], "no": k[1], "m": k[2], "l": v} for k, v in groups.items()]

src = ("Contains OS data © Crown copyright and database right (OGL v3): OS Open Greenspace, OS Open Roads; borough boundaries excluding the Thames (London Datastore / ONS, OGL). "
       "Via jreades/fsds (UCL CASA). Converted from British National Grid with a ~5 m Helmert transform; "
       "simplified to 3–5 m.")
OUT.write_text("/* generated by scripts/build_osbase.py */\nwindow.ATLAS_OS=" + json.dumps(
    {"source": src, "land": land, "water": water, "green": green, "roads": roads}, separators=(",", ":")) + ";\n")
print(f"land {len(land)} water {len(water)} green {len(green)} roads {len(roads)} -> {OUT.stat().st_size // 1024} KB")
