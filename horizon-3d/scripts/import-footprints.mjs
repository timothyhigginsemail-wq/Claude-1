#!/usr/bin/env node
// Import exact present-day footprints from an NYC Open Data "Building Footprints"
// GeoJSON export (https://data.cityofnewyork.us — search "Building Footprints").
//
//   npm run import-footprints -- path/to/building_footprints.geojson
//
// Keeps buildings whose centroid lies inside the model extent, converts their
// lon/lat rings into the model's grid metres and writes
// src/data/footprints.generated.js. Field names differ between dataset
// versions, so several spellings are accepted.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { latLonToGrid } from '../src/geo.js';

const EXTENT = { u0: -250, u1: 260, v0: -175, v1: 250 };
const FT = 0.3048;

export function convert(geojson) {
  const out = [];
  for (const f of geojson.features || []) {
    const p = f.properties || {};
    const g = f.geometry;
    if (!g) continue;
    const polys = (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [])
      .map((rings) => rings[0].map(([lon, lat]) => { const { u, v } = latLonToGrid(lat, lon); return [+u.toFixed(2), +v.toFixed(2)]; }))
      .map((ring) => (ring.length > 1 && ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1] ? ring.slice(0, -1) : ring))
      .filter((ring) => ring.length >= 3);
    if (!polys.length) continue;
    const pts = polys.flat();
    const cu = pts.reduce((s, q) => s + q[0], 0) / pts.length;
    const cv = pts.reduce((s, q) => s + q[1], 0) / pts.length;
    if (cu < EXTENT.u0 || cu > EXTENT.u1 || cv < EXTENT.v0 || cv > EXTENT.v1) continue;
    const yr = Number(p.cnstrct_yr ?? p.construction_year ?? p.CNSTRCT_YR ?? 0);
    const hFt = Number(p.heightroof ?? p.height_roof ?? p.HEIGHTROOF ?? 0);
    out.push({
      id: String(p.doitt_id ?? p.DOITT_ID ?? p.bin ?? out.length),
      bin: p.bin ?? p.BIN ?? null,
      name: p.name ?? p.NAME ?? null,
      built: yr > 1600 ? yr : 1900,
      builtRaw: yr > 1600 ? yr : null,
      height: Math.max(3, +(hFt * FT).toFixed(1) || 12),
      polys,
    });
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  if (!file) {
    console.error('usage: npm run import-footprints -- <building_footprints.geojson>');
    process.exit(1);
  }
  const rows = convert(JSON.parse(readFileSync(file, 'utf8')));
  const dest = new URL('../src/data/footprints.generated.js', import.meta.url);
  writeFileSync(dest, `// Generated by scripts/import-footprints.mjs from ${file.split('/').pop()} — do not edit.\nexport default ${JSON.stringify(rows)};\n`);
  console.log(`Imported ${rows.length} footprints into ${fileURLToPath(dest)}`);
}
